"""
fix_selector_precision.py
Two small improvements to semantic selectors generated by fix_restore_semantic_selectors.py:

1. CSS: add direct-child combinators before ul and li
   e.g. ".description-summary ul li:first-child"
     -> ".description-summary > ul > li:first-child"

2. XPath: use // between intermediate class nodes (not /)
   e.g. "//*[contains(@class,'prop-info')]/*[contains(@class,'description-summary')]"
     -> "//*[contains(@class,'prop-info')]//*[contains(@class,'description-summary')]"
"""

import json, os, re

GOLD_DIR = r'd:\PhD\myArticlesAndPapers\my-papers\5-WISE\wade-bench\data\gold\by_task\realestate'


def fix_css(css):
    if not css:
        return css
    # Add > before ul and li where missing (not already > ul or > li)
    # Pattern: class-selector space ul space li:... -> > ul > li:...
    # Step 1: "ul li:" -> "ul > li:"
    css = re.sub(r'\bul\s+li:', 'ul > li:', css)
    # Step 2: ".something ul" -> ".something > ul"  (only when preceded by class/tag selector)
    css = re.sub(r'(\w|\))\s+ul\b', r'\1 > ul', css)
    return css


def fix_xpath(xpath):
    if not xpath:
        return xpath
    # Change //*[contains]/*[contains] -> //*[contains]//*[contains]
    # i.e. between two consecutive class-contains predicates, use // not /
    xpath = re.sub(
        r'(\*\[contains\(@class,[^\]]+\)\])/(\*\[contains\(@class)',
        r'\1//\2',
        xpath
    )
    return xpath


files = sorted([f for f in os.listdir(GOLD_DIR) if f.endswith('.json')])

total_css = 0
total_xpath = 0

for fname in files:
    fpath = os.path.join(GOLD_DIR, fname)
    with open(fpath, 'r', encoding='utf-8') as f:
        data = json.load(f)

    changes = 0
    for rec in data.get('records', []):
        prov = rec.get('provenance', {})
        for field_name, pv in prov.items():
            if not isinstance(pv, dict):
                continue

            css = pv.get('css_selector', '')
            xpath = pv.get('xpath', '')

            new_css = fix_css(css)
            new_xpath = fix_xpath(xpath)

            if new_css != css:
                pv['css_selector'] = new_css
                changes += 1
                total_css += 1

            if new_xpath != xpath:
                pv['xpath'] = new_xpath
                changes += 1
                total_xpath += 1

    with open(fpath, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    if changes > 0:
        print('%-60s  changes=%d' % (fname, changes))

print('\nCSS fixes: %d | XPath fixes: %d' % (total_css, total_xpath))
print('Done.')
